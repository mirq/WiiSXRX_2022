#!/usr/bin/env python3
"""variables.txt -> wsx_vars.h (the launcher's table) and a plain-text reference."""
import sys, textwrap
src, hdr, txt = sys.argv[1:4]
rows = []
for line in open(src):
    line = line.strip()
    if not line or line.startswith('#'):
        continue
    g, n, d, desc = [p.strip() for p in line.split('|', 3)]
    rows.append((g, n, d, desc))
def c(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
with open(hdr, 'w') as f:
    f.write('/* Generated by mkvars.py from variables.txt: do not edit. */\n')
    f.write('static const char *const var_groups[] = {\n')
    groups = []
    for g, *_ in rows:
        if g not in groups: groups.append(g)
    for g in groups: f.write('    %s,\n' % c(g))
    f.write('};\n#define NGROUPS %d\n' % len(groups))
    f.write('static const struct WsxVar { UBYTE group; const char *name, *def, *desc; } vars[] = {\n')
    for g, n, d, desc in rows:
        f.write('    { %d, %s, %s, %s },\n' % (groups.index(g), c(n), c(d), c(desc)))
    f.write('};\n#define NVARS %d\n' % len(rows))
with open(txt, 'w') as f:
    f.write('WiiStation ENV: variables\n=========================\n\n'
            'Set one from a Shell with  SetEnv NAME value  (UnSetEnv NAME to remove it),\n'
            'or in WiiStationGUI\'s Variables window, which sets them for one run only.\n'
            '"-" as the default means: not set, the feature is off.\n')
    last = None
    for g, n, d, desc in rows:
        if g != last:
            f.write('\n%s\n%s\n' % (g, '-' * len(g)))
            last = g
        f.write('\n%-20s default %s\n' % (n, d))
        f.write(textwrap.fill(desc, 72, initial_indent='    ', subsequent_indent='    ') + '\n')
print(len(rows), 'variables')
